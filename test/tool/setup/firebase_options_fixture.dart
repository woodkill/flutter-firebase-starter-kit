/// FlutterFire CLI 가 실제로 만드는 모양의 Dart 설정 파일 본문을 만든다.
///
/// 실제 생성본 모양 — 첫 줄 생성 마커 주석 · `ignore_for_file` · import ·
/// `currentPlatform` getter(web 검사 · 플랫폼 switch) · `android` · `ios` 정의를
/// FlutterFire CLI 템플릿과 같은 순서로 쓴다. 미지원 플랫폼(web · macOS ·
/// windows · linux · default)마다 예외 throw 를 포함한다 — 저장소 자리표시와
/// 구분하는 판정이 이 예외 문자열에 기대면 안 되기 때문이다.
///
/// 생성 마커 주석은 판정 쪽 상수를 참조하지 않고 리터럴로 쓴다 — 상수에 오타가
/// 있으면 판정과 fixture 가 같은 오타를 함께 가져 테스트가 잡지 못한다.
///
/// [apiKey] 는 호출하는 테스트가 실행 시점에 조립해 넘긴다. [iosBundleId] 가
/// 없으면 `ios` 정의에서 그 줄을 뺀다.
String buildGeneratedOptionsSource({
  required String projectId,
  required String apiKey,
  required String androidAppId,
  required String iosAppId,
  String? iosBundleId,
}) {
  final String iosBundleLine = iosBundleId == null
      ? ''
      : "    iosBundleId: '$iosBundleId',\n";
  return '''
// File generated by FlutterFire CLI.
// ignore_for_file: type=lint
import 'package:firebase_core/firebase_core.dart' show FirebaseOptions;
import 'package:flutter/foundation.dart'
    show defaultTargetPlatform, kIsWeb, TargetPlatform;

/// Default [FirebaseOptions] for use with your Firebase apps.
///
/// Example:
/// ```dart
/// import 'firebase_options_dev.dart';
/// // ...
/// await Firebase.initializeApp(
///   options: DefaultFirebaseOptions.currentPlatform,
/// );
/// ```
class DefaultFirebaseOptions {
  static FirebaseOptions get currentPlatform {
    if (kIsWeb) {
      throw UnsupportedError(
        'DefaultFirebaseOptions have not been configured for web - '
        'you can reconfigure this by running the FlutterFire CLI again.',
      );
    }
    switch (defaultTargetPlatform) {
      case TargetPlatform.android:
        return android;
      case TargetPlatform.iOS:
        return ios;
      case TargetPlatform.macOS:
        throw UnsupportedError(
          'DefaultFirebaseOptions have not been configured for macos - '
          'you can reconfigure this by running the FlutterFire CLI again.',
        );
      case TargetPlatform.windows:
        throw UnsupportedError(
          'DefaultFirebaseOptions have not been configured for windows - '
          'you can reconfigure this by running the FlutterFire CLI again.',
        );
      case TargetPlatform.linux:
        throw UnsupportedError(
          'DefaultFirebaseOptions have not been configured for linux - '
          'you can reconfigure this by running the FlutterFire CLI again.',
        );
      default:
        throw UnsupportedError(
          'DefaultFirebaseOptions are not supported for this platform.',
        );
    }
  }

  static const FirebaseOptions android = FirebaseOptions(
    apiKey: '$apiKey',
    appId: '$androidAppId',
    messagingSenderId: '000000000000',
    projectId: '$projectId',
    storageBucket: '$projectId.firebasestorage.app',
  );

  static const FirebaseOptions ios = FirebaseOptions(
    apiKey: '$apiKey',
    appId: '$iosAppId',
    messagingSenderId: '000000000000',
    projectId: '$projectId',
    storageBucket: '$projectId.firebasestorage.app',
$iosBundleLine  );
}
''';
}
